BEGIN;

CREATE TABLE IF NOT EXISTS public.chat_mensaje_supermercado (
  id_mensaje bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  id_super uuid NOT NULL REFERENCES public.super (id_super) ON DELETE CASCADE,
  id_usuario uuid NOT NULL REFERENCES public.usuario (id_usuario) ON DELETE CASCADE,
  mensaje text NOT NULL,
  creado_en timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT chat_mensaje_supermercado_mensaje_length
    CHECK (pg_catalog.char_length(pg_catalog.btrim(mensaje)) BETWEEN 1 AND 500)
);

CREATE INDEX IF NOT EXISTS chat_mensaje_supermercado_recent_idx
  ON public.chat_mensaje_supermercado (id_super, id_mensaje DESC);

ALTER TABLE public.chat_mensaje_supermercado ENABLE ROW LEVEL SECURITY;
REVOKE ALL ON TABLE public.chat_mensaje_supermercado FROM PUBLIC, anon, authenticated;

CREATE OR REPLACE FUNCTION public.obtener_mensajes_supermercado(
  p_id_super uuid,
  p_ultimo_id bigint DEFAULT 0
)
RETURNS TABLE (
  id_mensaje bigint,
  mensaje text,
  creado_en timestamptz,
  nombre_usuario text,
  es_mio boolean
)
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = ''
AS $$
DECLARE
  v_usuario_id uuid;
BEGIN
  IF auth.uid() IS NULL THEN
    RAISE EXCEPTION 'Debes iniciar sesión para entrar al chat.';
  END IF;
  IF p_id_super IS NULL OR p_ultimo_id < 0 THEN
    RAISE EXCEPTION 'El supermercado o el cursor del chat no son válidos.';
  END IF;

  SELECT usuario_row.id_usuario
  INTO v_usuario_id
  FROM public.usuario AS usuario_row
  WHERE usuario_row.auth_id = auth.uid();

  IF v_usuario_id IS NULL THEN
    RAISE EXCEPTION 'No se encontró un perfil de usuario para entrar al chat.';
  END IF;

  IF NOT EXISTS (
    SELECT 1
    FROM public.super AS super_row
    WHERE super_row.id_super = p_id_super
  ) THEN
    RAISE EXCEPTION 'No se encontró el supermercado solicitado.';
  END IF;

  RETURN QUERY
  SELECT
    recent.id_mensaje,
    recent.mensaje,
    recent.creado_en,
    recent.nombre_usuario,
    recent.id_usuario = v_usuario_id
  FROM (
    SELECT
      chat_row.id_mensaje,
      chat_row.mensaje,
      chat_row.creado_en,
      usuario_row.nombre::text AS nombre_usuario,
      chat_row.id_usuario
    FROM public.chat_mensaje_supermercado AS chat_row
    JOIN public.usuario AS usuario_row
      ON usuario_row.id_usuario = chat_row.id_usuario
    WHERE chat_row.id_super = p_id_super
      AND (p_ultimo_id = 0 OR chat_row.id_mensaje > p_ultimo_id)
    ORDER BY chat_row.id_mensaje DESC
    LIMIT CASE WHEN p_ultimo_id = 0 THEN 100 ELSE 500 END
  ) AS recent
  ORDER BY recent.id_mensaje;
END;
$$;

CREATE OR REPLACE FUNCTION public.enviar_mensaje_supermercado(
  p_id_super uuid,
  p_mensaje text
)
RETURNS TABLE (
  id_mensaje bigint,
  mensaje text,
  creado_en timestamptz,
  nombre_usuario text,
  es_mio boolean
)
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = ''
AS $$
DECLARE
  v_usuario_id uuid;
  v_mensaje_id bigint;
BEGIN
  IF auth.uid() IS NULL THEN
    RAISE EXCEPTION 'Debes iniciar sesión para enviar mensajes.';
  END IF;
  IF p_id_super IS NULL
    OR NULLIF(pg_catalog.btrim(p_mensaje), '') IS NULL
    OR pg_catalog.char_length(pg_catalog.btrim(p_mensaje)) > 500
  THEN
    RAISE EXCEPTION 'El mensaje debe contener entre 1 y 500 caracteres.';
  END IF;

  SELECT usuario_row.id_usuario
  INTO v_usuario_id
  FROM public.usuario AS usuario_row
  WHERE usuario_row.auth_id = auth.uid();

  IF v_usuario_id IS NULL THEN
    RAISE EXCEPTION 'No se encontró un perfil de usuario para enviar mensajes.';
  END IF;

  INSERT INTO public.chat_mensaje_supermercado AS inserted_row (
    id_super,
    id_usuario,
    mensaje
  )
  VALUES (
    p_id_super,
    v_usuario_id,
    pg_catalog.btrim(p_mensaje)
  )
  RETURNING inserted_row.id_mensaje
  INTO v_mensaje_id;

  RETURN QUERY
  SELECT
    chat_row.id_mensaje,
    chat_row.mensaje,
    chat_row.creado_en,
    usuario_row.nombre::text,
    true
  FROM public.chat_mensaje_supermercado AS chat_row
  JOIN public.usuario AS usuario_row
    ON usuario_row.id_usuario = chat_row.id_usuario
  WHERE chat_row.id_mensaje = v_mensaje_id;
END;
$$;

REVOKE ALL ON FUNCTION public.obtener_mensajes_supermercado(uuid, bigint)
  FROM PUBLIC, anon, authenticated;
REVOKE ALL ON FUNCTION public.enviar_mensaje_supermercado(uuid, text)
  FROM PUBLIC, anon, authenticated;
GRANT EXECUTE ON FUNCTION public.obtener_mensajes_supermercado(uuid, bigint)
  TO authenticated;
GRANT EXECUTE ON FUNCTION public.enviar_mensaje_supermercado(uuid, text)
  TO authenticated;

NOTIFY pgrst, 'reload schema';

COMMIT;
